"""Report and case-file exports built only from real investigation results.

* Markdown report: human-readable, conclusion first, every statement with
  its citations (chunk IDs + file paths) so it can be checked offline.
* JSON case file: the structured result (question, plan, evidence passages,
  timeline, analyzer findings, verified claims, open questions) for every
  turn of an investigation, for audit or archiving.

No values are added that are not present on the result objects.
"""

from __future__ import annotations

import json
from datetime import date, datetime, timezone
from enum import Enum

from app import ui as U
from app.command_center import data as D

EXPORT_NOTE = (
    "Generated by TRACE from the evidence retrieved for this investigation. "
    "Decision support only: TRACE does not approve or authorize production changes."
)


def _value(obj):
    if isinstance(obj, Enum):
        return obj.value
    if isinstance(obj, (date, datetime)):
        return obj.isoformat()
    return obj


def _claim_dict(claim, evidence_ids=None) -> dict:
    return {
        "statement": str(getattr(claim, "statement", "")),
        "display_statement": U._display_claim_statement(claim),
        "stance": _value(getattr(claim, "stance", None)),
        "status_label": D.claim_status(claim, evidence_ids)[0],
        # Lexical identifier check only (see ReasoningClaim.citation_check),
        # never semantic support.
        "citation_check": str(getattr(claim, "citation_check", "") or ""),
        "claim_type": _value(getattr(claim, "claim_type", None)),
        "calibrated_confidence": float(getattr(claim, "confidence", 0.0) or 0.0),
        "evidence_chunk_ids": list(getattr(claim, "evidence_chunk_ids", []) or []),
    }


def result_to_dict(result, meta: dict | None = None) -> dict:
    report = getattr(result, "report", None)
    investigation = getattr(result, "investigation", None)
    label, _tone = U._assessment_label(result)
    run = (meta or {}).get("retrieval_run") or {}
    return {
        "question": str(getattr(investigation, "question", "")),
        "assessment": label,
        "direct_answer": U._clean_direct_answer(getattr(report, "direct_answer", "") or ""),
        "direct_answer_evidence_chunk_ids": list(getattr(report, "direct_answer_evidence_chunk_ids", []) or []),
        "subquestions": list(getattr(getattr(result, "plan", None), "subquestions", []) or []),
        "claims": [_claim_dict(c, D.evidence_ids(result)) for c in U._claims(result)],
        "analyzer_findings": [
            {
                "finding_type": U._finding_kind(f),
                "statement": str(getattr(f, "statement", "")),
                "evidence_chunk_ids": list(getattr(f, "evidence_chunk_ids", []) or []),
            }
            for f in U._findings(result)
        ],
        "unresolved_questions": U._unresolved(result),
        "timeline_events": [
            {
                "date": _value(getattr(e, "date", None)),
                "description": str(getattr(e, "description", "")),
                "evidence_chunk_ids": list(getattr(e, "evidence_chunk_ids", []) or []),
            }
            for e in list(getattr(getattr(result, "timeline", None), "events", []) or [])
        ],
        "evidence": [
            {
                "chunk_id": e.chunk_id,
                "document_id": getattr(e, "document_id", ""),
                "filename": e.filename,
                "relative_path": e.relative_path,
                "retrieval_score": float(e.retrieval_score or 0.0),
                "retrieval_channels": list(getattr(e, "retrieval_channels", []) or []),
                "retrieved_for": list(getattr(e, "retrieved_for", []) or []),
                "content": e.content,
            }
            for e in U._evidence_items(result)
        ],
        "retrieval_run": {k: v for k, v in run.items() if isinstance(v, (int, float, str)) or v is None},
    }


def case_to_json(conversation: dict) -> str:
    turns = []
    for index, turn in enumerate(conversation.get("turns", []), start=1):
        entry = {
            "turn": index,
            "kind": turn.get("kind"),
            "question": turn.get("question"),
            "created_at": turn.get("created_at"),
        }
        if turn.get("result") is not None:
            entry["result"] = result_to_dict(turn["result"], turn.get("meta"))
        else:
            entry["message"] = turn.get("message", "")
        turns.append(entry)
    payload = {
        "format": "trace-case/1",
        "exported_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "note": EXPORT_NOTE,
        "investigation_id": conversation.get("id"),
        "title": conversation.get("title"),
        "turns": turns,
    }
    return json.dumps(payload, indent=2, ensure_ascii=False, default=_value)


def _cite(result, chunk_ids) -> str:
    by_id = U._evidence_by_id(result)
    parts = []
    for chunk_id in chunk_ids or []:
        item = by_id.get(chunk_id)
        parts.append(f"`{chunk_id}`" + (f" ({item.relative_path})" if item is not None else " (unresolved)"))
    return "; ".join(parts) if parts else "no valid citation"


def result_to_markdown(result, meta: dict | None = None, turn_label: str = "") -> str:
    lines: list[str] = []
    question = str(getattr(getattr(result, "investigation", None), "question", ""))
    label, _ = U._assessment_label(result)
    _l, statement, _t, confidence, requires_human = U._assessment(result)
    primary = U._primary_claim(result)
    if primary is not None:
        statement = U._display_claim_statement(primary)

    lines.append(f"## {turn_label + ' · ' if turn_label else ''}{question}")
    lines.append("")
    lines.append(f"**Assessment:** {label}  ")
    lines.append(
        f"**Evidence strength (assessed claim):** {U._evidence_strength(confidence)} "
        f"({confidence:.0%} calibrated confidence for that claim only)  "
    )
    lines.append(f"**Human verification required:** {'Yes' if requires_human else 'No'}")
    lines.append("")
    lines.append(f"> {statement}")
    lines.append("")

    answer = U._clean_direct_answer(getattr(result.report, "direct_answer", "") or "")
    if answer:
        lines.append("### Direct answer")
        lines.append(answer)
        lines.append("")
        lines.append(f"Citations: {_cite(result, getattr(result.report, 'direct_answer_evidence_chunk_ids', []))}")
        lines.append("")

    groups = D.grouped_claims(result)
    if any(groups.values()):
        lines.append("### Claims (verified after reasoning)")
        for key, rows in groups.items():
            if not rows:
                continue
            title = D.CLAIM_GROUPS[key][0]
            lines.append(f"#### {title}")
            for row in rows:
                lines.append(
                    f"- **{row.status_label}** · {row.type_label} · {row.confidence:.0%} — {row.statement}  "
                )
                lines.append(f"  Evidence: {_cite(result, row.chunk_ids)}")
            lines.append("")

    register = D.gap_register(result)
    if register:
        lines.append("### Gaps, contradictions and next steps")
        for kind, (title, _tone) in D.REGISTER_KINDS.items():
            items = [i for i in register if i.kind == kind]
            if not items:
                continue
            lines.append(f"#### {title}")
            for item in items:
                cite = f" — {_cite(result, item.chunk_ids)}" if item.chunk_ids else ""
                lines.append(f"- {item.statement} _({item.origin})_{cite}")
            lines.append("")

    rows, total = D.timeline_rows(result)
    rows = [r for r in rows if r.key]
    if rows:
        lines.append("### Timeline (dates extracted from retrieved records)")
        if total > len(rows):
            lines.append(f"_Showing {len(rows)} key entries built from {total} extracted dated events._")
        for row in rows:
            lines.append(f"- **{row.date_label}** — {row.headline} ({', '.join(row.chunk_ids[:3])})")
        lines.append("")

    evidence = U._evidence_items(result)
    if evidence:
        cited = D.cited_chunk_ids(result)
        lines.append("### Cited sources")
        for item in evidence:
            if item.chunk_id in cited:
                lines.append(f"- `{item.chunk_id}` — {item.relative_path}")
        lines.append(f"\n_{len(evidence)} passages were retrieved in total._")
        lines.append("")
    return "\n".join(lines)


def case_to_markdown(conversation: dict) -> str:
    out = [
        f"# TRACE investigation report — {conversation.get('title', '')}",
        "",
        f"_Exported {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}. {EXPORT_NOTE}_",
        "",
    ]
    turns = conversation.get("turns", [])
    for index, turn in enumerate(turns, start=1):
        label = f"Turn {index}" if len(turns) > 1 else ""
        if turn.get("result") is None:
            out.append(f"## {label + ' · ' if label else ''}{turn.get('question', '')}")
            out.append("")
            out.append(f"_No investigation was run:_ {turn.get('message', '')}")
            out.append("")
            continue
        out.append(result_to_markdown(turn["result"], turn.get("meta"), label))
    return "\n".join(out)
